public static class Loc
{
    public static AppLanguage Current { get; set; } = DetectDefaultLanguage();

    public static AppLanguage DetectDefaultLanguage()
    {
        return CultureInfo.CurrentUICulture.TwoLetterISOLanguageName.ToLowerInvariant() switch
        {
            "ru" => AppLanguage.Ru,
            "zh" => AppLanguage.Zh,
            "de" => AppLanguage.De,
            _ => AppLanguage.En
        };
    }

    public static IReadOnlyCollection<string> AllKeys => Strings[AppLanguage.En].Keys;

    public static string Get(string key) => Get(Current, key);

    public static string Get(AppLanguage lang, string key)
    {
        if (Strings.TryGetValue(lang, out var dict) && dict.TryGetValue(key, out string? val))
            return val;
        if (Strings[AppLanguage.En].TryGetValue(key, out string? enVal))
            return enVal;
        return key;
    }

    public static bool TryGetExact(AppLanguage lang, string key, out string value)
    {
        value = string.Empty;
        return Strings.TryGetValue(lang, out var dict) && dict.TryGetValue(key, out value!);
    }

    public static string Format(string key, params object[] args) =>
        string.Format(CultureInfo.CurrentCulture, Get(key), args);

    public static string GetLightingModeName(byte mode) => GetLightingModeName(Current, mode);

    public static string GetLightingModeName(AppLanguage lang, byte mode)
    {
        if (ModeNames.TryGetValue(lang, out var list) && mode < list.Length)
            return $"{mode}: {list[mode]}";
        var en = ModeNames[AppLanguage.En];
        return mode < en.Length ? $"{mode}: {en[mode]}" : $"Mode {mode}";
    }

